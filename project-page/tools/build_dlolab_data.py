"""Build project-page/static/js/dlolab_fit.js from a DLO-Lab general-fit state file.

Run from the repository root:
    python project-page/tools/build_dlolab_data.py .
    python project-page/tools/build_dlolab_data.py . --state dlolab_fit_t36/results/<run>/dlolab_general_fit_t36.json

Default state: dlolab_fit_t36/state/dlolab_general_fit_t36_gen21.json (the main machine's run, generation 21).
Bounds and the parameter layout are those of dlolab_fit_t36/scripts/dlolab_general_fit_cmaes.py.
Means only: the owner's rule is to never show a median.
"""
import argparse, json
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("root")
ap.add_argument("--state", default="dlolab_fit_t36/state/dlolab_general_fit_t36_gen21.json")
ap.add_argument("--mass-max", type=float, default=0.5, help="upper mass bound used by the run (run_dlolab_t36.sh: 0.5)")
a = ap.parse_args()
root = Path(a.root)
st = json.loads((root / a.state).read_text(encoding="utf-8"))
warm = json.loads((root / "dlolab_fit_t36/data/genesis_rod_allclip_best.json").read_text(encoding="utf-8"))

hist = [{"gen": h["gen"], "best": h["best"], "best_ever": h.get("best_ever", h["best"])} for h in st["hist"]]
best_gen = min(hist, key=lambda h: h["best"])["gen"]

out = {
    "source": a.state,
    "best_f": st["best_f"],
    "base_f": st["base_f"],
    "best_gen": best_gen,
    "last_gen": hist[-1]["gen"],
    "hist": hist,
    "n_params": len(st["best_x"]),
    "groups": [
        {"label": "Rest curvature", "n": 112, "detail": "4 cables x 14 hinges x 2 components"},
        {"label": "Stretch scale", "n": 60, "detail": "4 cables x 15 edges"},
        {"label": "Bending (hinge) scale", "n": 56, "detail": "4 cables x 14 hinges"},
        {"label": "Twist scale", "n": 56, "detail": "4 cables x 14 hinges"},
        {"label": "Global (K, E, G, μ, damping, 4 masses)", "n": 9, "detail": "shared constants + one mass per cable"},
    ],
    "globals": [
        {"key": "K", "label": "K (stretch stiffness)", "value": st["K"], "lo": 1e2, "hi": 1e7, "scale": "log", "warm": warm["K"]},
        {"key": "E", "label": "E (Young's modulus)", "value": st["E"], "lo": 1e3, "hi": 1e9, "scale": "log", "warm": warm["E"]},
        {"key": "G", "label": "G (shear modulus)", "value": st["G"], "lo": 0.0, "hi": 9e5, "scale": "sqrt", "warm": warm.get("G", 0.0)},
        {"key": "mu", "label": "μ (cable-board friction)", "value": st["mu"], "lo": 0.02, "hi": 2.0, "scale": "log", "warm": 0.1},
        {"key": "damping", "label": "Velocity damping", "value": st["damping"], "lo": 4.0, "hi": 400.0, "scale": "log", "warm": 40.0},
    ],
    "mass": {"values": st["mass_per_m"], "lo": 0.02, "hi": a.mass_max, "warm": 0.045, "unit": "kg/m"},
    "perJoint": {
        "hinge": {"label": "Bending (hinge) scale", "unit": "×", "kind": "scale", "lo": 0.05, "hi": 20.0, "values": st["hinge_scale"], "axis": "hinge"},
        "stretch": {"label": "Stretch scale", "unit": "×", "kind": "scale", "lo": 0.05, "hi": 20.0, "values": st["stretch_scale"], "axis": "edge"},
        "twist": {"label": "Twist scale", "unit": "×", "kind": "scale", "lo": 0.05, "hi": 20.0, "values": st["twist_scale"], "axis": "hinge"},
        "kappa1": {"label": "Rest curvature κ₁", "unit": "1/m", "kind": "signed", "lo": -0.5, "hi": 0.5,
                   "values": [[k[0] for k in cable] for cable in st["kappa_rest"]], "axis": "hinge"},
        "kappa2": {"label": "Rest curvature κ₂", "unit": "1/m", "kind": "signed", "lo": -0.5, "hi": 0.5,
                   "values": [[k[1] for k in cable] for cable in st["kappa_rest"]], "axis": "hinge"},
    },
    "run": {"popsize": 20, "sims_per_gen": 720, "sec_per_gen": 7900, "workers": 12, "backend": "CPU",
            "stopped": "2026-11-04 (RAM limit on the main machine); continued on another machine from this state"},
}
dst = root / "project-page/static/js/dlolab_fit.js"
dst.write_text("// Generated by project-page/tools/build_dlolab_data.py from " + a.state + ". Do not edit by hand.\n"
               "window.DLOLAB_FIT = " + json.dumps(out, indent=1) + ";\n", encoding="utf-8")
print("wrote", dst, "| best", round(out["best_f"], 3), "at gen", best_gen, "| start", round(out["base_f"], 3),
      "| gens", out["last_gen"], "| params", out["n_params"])

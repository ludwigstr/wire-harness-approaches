"""Build project-page/static/js/physworld_phi.js from the PhysWorld per-clip GNN files.

Each physworld_mpm/data/gnn/<clip>.json holds the per-node Phi of one clip:
  phi_twin   (4 cables, 16 nodes, 2)  the twin's value, the starting point
  phi_fitted (4 cables, 16 nodes, 2)  after fine-tuning on the real clip (network frozen)
Channel 0 is log E (Young's modulus, Pa), channel 1 is log rho (density, kg/m^3).

Run from the repository root:  python project-page/tools/build_physworld_phi.py .
"""
import json
import math
import sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else ".")
src = root / "physworld_mpm" / "data" / "gnn"


def sig(v, n=4):
    return float(f"{v:.{n}g}")


clips = []
box = None
for f in sorted(src.glob("*.json")):
    d = json.loads(f.read_text(encoding="utf-8"))
    box = d.get("phi_box", box)

    def chan(key, c):
        return [[sig(math.exp(node[c])) for node in cable] for cable in d[key]]

    clips.append({
        "clip": d["clip"],
        "mean": round(d["mittel"], 3),
        "before": round(d["mittel_before_phi_finetune"], 3),
        "frames": d.get("n_frames"),
        "E": {"fit": chan("phi_fitted", 0), "twin": chan("phi_twin", 0)},
        "rho": {"fit": chan("phi_fitted", 1), "twin": chan("phi_twin", 1)},
    })

out = {"source": "physworld_mpm/data/gnn/<clip>.json (14-clip run, one GNN per clip)", "box": box, "clips": clips}
dst = root / "project-page" / "static" / "js" / "physworld_phi.js"
dst.write_text("// Generated by tools/build_physworld_phi.py from physworld_mpm/data/gnn. Do not edit by hand.\n"
               "window.PHYSWORLD_PHI = " + json.dumps(out, separators=(",", ":")) + ";\n", encoding="utf-8")
print("clips", len(clips), "box", box, "->", dst)
